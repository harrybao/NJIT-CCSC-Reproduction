"""Resolve every CCSC "Citation" button to its citation text.

On https://nature.njit.edu/solardb/ccsc the tiles are generated by
js/script.js::getGenericPage() from ccsc_pages/pages_data.json; each tile's
"Citation" button is a link to the tool's Zenodo record. Zenodo itself timed out
(HTTP 504) from our environment, so we resolve the record DOI
(10.5281/zenodo.<record>) through DataCite, where Zenodo registers the same
metadata that its "Cite as" box shows:
  * APA text and BibTeX via doi.org content negotiation
  * full DataCite JSON (creators, version, year, related identifiers such as
    the journal paper and the GitHub release)
Usage: python fetch_ccsc_citations.py pages_data.json out_dir
"""
import json
import os
import re
import sys
import time
import urllib.request

pages, out = sys.argv[1], sys.argv[2]
os.makedirs(out, exist_ok=True)


def get(url, accept=None, tries=4):
    for i in range(tries):
        try:
            req = urllib.request.Request(url, headers={"Accept": accept} if accept else {})
            with urllib.request.urlopen(req, timeout=60) as r:
                return r.read().decode("utf-8")
        except Exception as e:  # network hiccups: back off and retry
            err = e
            time.sleep(2 ** (i + 1))
    return f"ERROR: {err}"


rows = []
for p in json.load(open(pages)):
    rec = re.search(r"records?/(\d+)", p["zenodo"]).group(1)
    doi = f"10.5281/zenodo.{rec}"
    apa = get(f"https://doi.org/{doi}", "text/x-bibliography; style=apa")
    bib = get(f"https://doi.org/{doi}", "application/x-bibtex")
    meta_txt = get(f"https://api.datacite.org/dois/{doi}")
    try:
        a = json.loads(meta_txt)["data"]["attributes"]
    except Exception:
        a = {}
    rel = [{"relationType": r.get("relationType"), "relatedIdentifier": r.get("relatedIdentifier"),
            "relatedIdentifierType": r.get("relatedIdentifierType")} for r in a.get("relatedIdentifiers", [])]
    row = {"page": p["page"], "ccsc_tile_title": p["title"], "github_repo": "https://github.com/ccsc-tools/" + p["repo"],
           "citation_button_url": p["zenodo"], "zenodo_doi": doi,
           "citation_apa": apa.strip(), "citation_bibtex": bib.strip(),
           "zenodo_title": (a.get("titles") or [{}])[0].get("title"), "version": a.get("version"),
           "publication_year": a.get("publicationYear"),
           "creators": [c.get("name") for c in a.get("creators", [])],
           "related_identifiers": rel,
           "description_first_300": re.sub("<[^>]+>", " ", (a.get("descriptions") or [{}])[0].get("description", ""))[:300]}
    rows.append(row)
    json.dump(json.loads(meta_txt) if meta_txt.startswith("{") else {"error": meta_txt},
              open(os.path.join(out, f"datacite_{p['page']}.json"), "w"), indent=1)
    print(p["page"], "|", row["version"], "|", row["publication_year"], "|", apa[:110].replace("\n", " "))
json.dump(rows, open(os.path.join(out, "ccsc_citations.json"), "w"), indent=1, ensure_ascii=False)
with open(os.path.join(out, "ccsc_citations.bib"), "w") as f:
    f.write("\n\n".join(r["citation_bibtex"] for r in rows) + "\n")
